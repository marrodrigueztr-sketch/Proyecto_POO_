    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String sku = txtSku.getText().trim().toUpperCase();
        String nombre = txtNombre.getText().trim();
        String proveedor = txtProveedor.getText().trim();
        String tipo = (String) cmbTipo.getSelectedItem();
        if (txtId.getText().isBlank() || sku.isEmpty() || nombre.isEmpty() || proveedor.isEmpty()
                || txtPrecio.getText().isBlank() || txtStock.getText().isBlank()) {
            aviso("Todos los campos son obligatorios.");
            return;
        }
        int id;
        float precio;
        int stock;
        try {
            id = Integer.parseInt(txtId.getText().trim());
            precio = Float.parseFloat(txtPrecio.getText().trim());
            stock = Integer.parseInt(txtStock.getText().trim());
        } catch (NumberFormatException e) {
            aviso("El ID y el Stock deben ser enteros, y el Precio un número.");
            return;
        }
        if (id <= 0 || precio < 0 || stock < 0) {
            aviso("El ID debe ser mayor que 0, y el precio y el stock no pueden ser negativos.");
            return;
        }
        if (controlador.consultarUno(id) != null) {
            aviso("Ya existe un producto con el ID " + id + ".");
            return;
        }

        Productos nuevo = new Productos(id, sku, nombre, "", precio, stock, proveedor, tipo);
        boolean insertado = controlador.insertar(nuevo);
        imprimir("Insertar " + nombre + " (SKU " + sku + "): " + insertado);
        if (insertado) {
            llenarTabla();
            limpiar();
        } else {
            aviso("No se agregó: el SKU " + sku + " ya existe (equals compara por SKU).");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

