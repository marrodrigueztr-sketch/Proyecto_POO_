    private void btnEjecutarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEjecutarActionPerformed
        int opcion = cmbOpcion.getSelectedIndex() + 1;
        switch (opcion) {
            case 1:
                controlador.ordenar();   // sort nativo por ID (usa compareTo de Productos)
                reporte("ORDENADO POR ID (sort nativo)");
                break;
            case 2:
                controlador.ordenar(1);  // Burbuja por stock, descendente
                reporte("ORDENADO POR STOCK DE MAYOR A MENOR (Burbuja)");
                break;
            case 3:
                controlador.ordenar(0);  // Burbuja por stock, ascendente
                reporte("ORDENADO POR STOCK DE MENOR A MAYOR (Burbuja)");
                break;
            case 4:
                reporte("REPORTE DE PRODUCTOS (toString)");
                break;
            default:
                aviso("Opción no válida.");
        }
        llenarTabla();
    }//GEN-LAST:event_btnEjecutarActionPerformed

