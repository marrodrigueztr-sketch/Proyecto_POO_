    private void llenarTabla() {
        javax.swing.table.DefaultTableModel modeloTab = (javax.swing.table.DefaultTableModel) tblEspecies.getModel();
        modeloTab.setRowCount(0); // Limpiar tabla

        for (modelo.Especie e : conEspecie.listaEspecies()) {
            modeloTab.addRow(new Object[]{
                e.getId(),
                e.getNombreComun()
            });
        }
}

