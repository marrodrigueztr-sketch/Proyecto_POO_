    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        if (txtId.getText().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el ID de la especie a buscar.");
        return;
    }

    try {
        int idBuscar = Integer.parseInt(txtId.getText());
        modelo.Especie objBuscar = new modelo.Especie();
        objBuscar.setId(idBuscar); 

        controlador.ControladorEspecie cont = new controlador.ControladorEspecie();
        modelo.Especie resultado = cont.consultarUno(objBuscar); 

        if (resultado != null) {
            txtNombreComun.setText(resultado.getNombreComun());
            txtNombreCientifico.setText(resultado.getNombreCientifico());
            javax.swing.JOptionPane.showMessageDialog(this, "Especie encontrada.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ninguna especie con ese ID.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "El ID debe ser un número.");
    }

    }//GEN-LAST:event_btnBuscarActionPerformed

