    private void llenarTablaEspecies() {
        javax.swing.table.DefaultTableModel modeloTab = new javax.swing.table.DefaultTableModel();
        modeloTab.addColumn("ID");
        modeloTab.addColumn("Nombre Común");
        modeloTab.addColumn("Nombre Científico");

        controlador.ControladorEspecie contEspecie = new controlador.ControladorEspecie();

         for (modelo.Especie e : contEspecie.listaEspecies()) {
            Object[] fila = { 
                e.getId(), 
                e.getNombreComun(), 
                e.getNombreCientifico() 
            };
            modeloTab.addRow(fila);
        }
        tblEspecies.setModel(modeloTab);
}
