    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
        //evita campos vacíos
        if(txtId.getText().isEmpty() || txtNombreComun.getText().isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "ID y Nombre Común son obligatorios.");
            return;
        }

        int id = Integer.parseInt(txtId.getText());
        String nComun = txtNombreComun.getText();
        String nCientifico = txtNombreCientifico.getText();

        modelo.Especie nueva = new modelo.Especie(id, nComun, nCientifico);
        controlador.ControladorEspecie cont = new controlador.ControladorEspecie();
        
        if(cont.insertar(nueva)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Especie guardada correctamente.");
            llenarTablaEspecies(); // Refresca la tabla
            // Limpiamos los campos
            txtId.setText(""); 
            txtNombreComun.setText(""); 
            txtNombreCientifico.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: El ID ya existe.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error: El ID debe ser un número entero.");
    }


    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblEspecies.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una fila de la tabla para eliminar.");
            return;
        }

        int id = Integer.parseInt(tblEspecies.getValueAt(fila, 0).toString());
        modelo.Especie obj = new modelo.Especie();
        obj.setId(id);

        controlador.ControladorEspecie cont = new controlador.ControladorEspecie();
        if(cont.borrar(obj)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Especie eliminada del sistema.");
            llenarTablaEspecies();
        }

    }//GEN-LAST:event_btnEliminarActionPerformed

