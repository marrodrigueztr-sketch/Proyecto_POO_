    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
        int id = Integer.parseInt(txtId.getText());
        String nombre = txtNombre.getText();

        modelo.Pais nuevoPais = new modelo.Pais(id, nombre);

        if (controlador.insertar(nuevoPais)) {
            javax.swing.JOptionPane.showMessageDialog(this, "País guardado correctamente.");
            llenarTabla(); // Actualizamos la tabla

      
            txtId.setText("");
            txtNombre.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Ya existe un pais con ese ID.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese un ID numerico valido.");
    }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
        int idBuscar = Integer.parseInt(txtId.getText());

        modelo.Pais paisTemporal = new modelo.Pais(idBuscar, "");

        modelo.Pais paisEncontrado = controlador.consultarUno(paisTemporal);

        if (paisEncontrado != null) {
            txtNombre.setText(paisEncontrado.getNombre());
            javax.swing.JOptionPane.showMessageDialog(this, "País encontrado.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "El país no existe en el sistema.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el ID del país que desea buscar.");
    }
        
        
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
        int id = Integer.parseInt(txtId.getText());
        String nombre = txtNombre.getText();

        modelo.Pais paisModificado = new modelo.Pais(id, nombre);

        if (controlador.modificar(paisModificado)) {
            javax.swing.JOptionPane.showMessageDialog(this, "País modificado con éxito.");
            llenarTabla(); 

            txtId.setText("");
            txtNombre.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró el país para modificar.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, busque un ID numérico válido para modificar.");
    }
        
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        try {
        int idEliminar = Integer.parseInt(txtId.getText());

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Está seguro que desea eliminar el país con ID " + idEliminar + "?", 
                "Confirmar eliminación", 
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            modelo.Pais paisTemporal = new modelo.Pais(idEliminar, "");

            if (controlador.borrar(paisTemporal)) {
                javax.swing.JOptionPane.showMessageDialog(this, "País eliminado correctamente.");
                llenarTabla(); // Refrescamos la tabla
                
                txtId.setText("");
                txtNombre.setText("");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo eliminar. El ID no existe.");
            }
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese el ID del país que desea eliminar.");
    }
        
        
    }//GEN-LAST:event_jButton4ActionPerformed

