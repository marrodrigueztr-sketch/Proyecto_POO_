    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // verificamos que fila seleccionó el usuario en la tabla
    int filaSeleccionada = tblFincas.getSelectedRow();
    
    if (filaSeleccionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione una finca de la tabla para eliminar.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
        return; // Detenemos la ejecución si no hay nada seleccionado
    }
    
    // cogemos el ID de la finca de esa fila    
    // Usamos toString() y luego Integer.parseInt para evitar errores de casteo de objetos
    int idFinca = Integer.parseInt(tblFincas.getValueAt(filaSeleccionada, 0).toString());
    
    //  confirmmamos al usuario 
    int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, "¿Está seguro de que desea eliminar la finca con ID " + idFinca + "?", "Confirmar Eliminación", javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {

        Finca fincaABorrar = new Finca();
        fincaABorrar.setIdFinca(idFinca); 
        

        ControladorFinca contFinca = new ControladorFinca();
        boolean exito = contFinca.borrar(fincaABorrar); 
        
        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "Finca eliminada exitosamente.");
            llenarTabla(); // Refrescamos la tabla para que desaparezca la fila
            
            // Limpiamos las cajas de texto por si quedaron con datos
            txtIdFinca.setText(""); 
            txtNombreFinca.setText("");
            txtDireccion.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: No se pudo eliminar la finca.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
        

    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String idBuscar = txtIdFinca.getText();
    
    if (idBuscar.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un ID para buscar.");
        return;
    }

    ControladorFinca contFinca = new ControladorFinca();
    Finca resultado = contFinca.consultarUno(new Finca(Integer.parseInt(idBuscar), "", ""));

    if (resultado != null) {
        txtNombreFinca.setText(resultado.getNombreFinca());
        txtDireccion.setText(resultado.getDireccionFinca());
        javax.swing.JOptionPane.showMessageDialog(this, "Finca encontrada.");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ninguna finca con ese ID.");
    }
            
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        int fila = tblFincas.getSelectedRow();

        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una fila de la tabla para modificar.");
            return;
        }

        // capturamos los nuevos datos de los campos
        int id = Integer.parseInt(txtIdFinca.getText());
        String nombre = txtNombreFinca.getText();
        String direccion = txtDireccion.getText();

        // objeto actualizado
        Finca fincaModificada = new Finca(id, nombre, direccion);
        ControladorFinca contFinca = new ControladorFinca();
        boolean exito = contFinca.modificar(fincaModificada);

        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "Finca modificada correctamente.");
            llenarTabla(); // Refresca la tabla con los nuevos datos
            btnLimpiarActionPerformed(null); // Limpia los campos
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al modificar.");
        }

    }//GEN-LAST:event_btnModificarActionPerformed

