    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // capturamos los datos
    String idTexto = txtIdFinca.getText();
    String nombre = txtNombreFinca.getText();
    String direccion = txtDireccion.getText();
    
    //  validacion
    if(idTexto.isEmpty() || nombre.isEmpty() || direccion.isEmpty()){
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor llene ID, Nombre y Dirección.", "Campos Vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    try {
        int id = Integer.parseInt(idTexto);
        
        // usamos elconstructor basico
        Finca nuevaFinca = new Finca(id, nombre, direccion);
        
        //lo enviamos al controlador
        ControladorFinca contFinca = new ControladorFinca();
        boolean exito = contFinca.insertar(nuevaFinca);
        
        // verificamos resultado
        if(exito){
            javax.swing.JOptionPane.showMessageDialog(this, "Finca guardada exitosamente.");
            llenarTabla(); // Refrescamos la tabla para ver la nueva finca
            
            // Limpiamos las cajas de texto
            txtIdFinca.setText("");
            txtNombreFinca.setText("");
            txtDireccion.setText("");
        } else {
            
            javax.swing.JOptionPane.showMessageDialog(this, "Error: El ID de la finca ya existe.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
    } catch (NumberFormatException e) {
        //  Si escriben letras en el ID
        javax.swing.JOptionPane.showMessageDialog(this, "El ID debe ser un número entero.", "Error de Formato", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    


//---------------------------------------------------------------------------------------------------------

    }//GEN-LAST:event_btnGuardarActionPerformed

