public void llenarTabla() {
    // definimos el modelo de la tabla
    DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("ID");
    modelo.addColumn("NOMBRE");
    modelo.addColumn("DIRECCIÓN");
    
    // Instanciamos el controlador 
    ControladorFinca contFinca = new ControladorFinca();
    
    // recorremos la lista de fincas y las agregamos a las filas
    for (Finca f : contFinca.getListaFincas()) {
        Object[] fila = { f.getIdFinca(), f.getNombreFinca(), f.getDireccionFinca()};
        modelo.addRow(fila);
    }
    
    
    tblFincas.setModel(modelo);
}
