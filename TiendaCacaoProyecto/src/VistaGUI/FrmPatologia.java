    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int id = Integer.parseInt(txtId.getText());
        String comun = txtNombreComun.getText();
        String cientifico = txtNombreCientifico.getText();

        modelo.Patologia p = new modelo.Patologia(id, comun, cientifico);

        if (conPatologia.insertar(p)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Patología guardada con éxito");
            llenarTabla();
            limpiarCampos();
            
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "El ID ya existe");
        }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        if (txtId.getText().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el ID de la patologia a buscar.");
        return;
    }

    try {
        int idBuscar = Integer.parseInt(txtId.getText());
        modelo.Especie objBuscar = new modelo.Especie();
        objBuscar.setId(idBuscar); 

        controlador.ControladorEspecie cont = new controlador.ControladorEspecie();
        modelo.Especie resultado = cont.consultarUno(objBuscar); 

        if (resultado != null) {
            txtNombreComun.setText(resultado.getNombreComun());
            txtNombreCientifico.setText(resultado.getNombreCientifico());
            javax.swing.JOptionPane.showMessageDialog(this, "palotogia encontrada.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ninguna patologia con ese ID.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "El ID debe ser un número.");
    }

    }//GEN-LAST:event_jButton5ActionPerformed

