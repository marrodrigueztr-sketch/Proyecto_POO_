    private void llenarTabla() {
        javax.swing.table.DefaultTableModel modeloTab = (javax.swing.table.DefaultTableModel) tblPatologias.getModel();
        modeloTab.setRowCount(0); 
        
        for (modelo.Patologia p : ControladorPatologia.getListaPatologias()) {
            modeloTab.addRow(new Object[]{
                p.getId(),
                p.getNombreComun(),
                p.getNombreCientifico()
            });
        }
    }
