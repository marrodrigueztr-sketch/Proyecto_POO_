    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
         int fila = tblPatologias.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una fila de la tabla para eliminar.");
            return;
        }

        int id = Integer.parseInt(tblPatologias.getValueAt(fila, 0).toString());
        modelo.Patologia obj = new modelo.Patologia();
        obj.setId(id);

        if(conPatologia.borrar(obj)) {
            javax.swing.JOptionPane.showMessageDialog(this, "patologia eliminada del sistema.");
            llenarTabla();
        }

    }//GEN-LAST:event_jButton2ActionPerformed

