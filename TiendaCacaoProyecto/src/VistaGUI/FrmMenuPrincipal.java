    // el metodo de aplicar los permisos -----------------------------------------------------------------------------------------
    private void aplicarPermisos() {
        // roles: 1=Admin, 2=Trabajador, 3=Propietario

        if (rolUsuario == 3) {
            // El Propietario es de solo lectura 
            menuGestion.setVisible(false); 
            menuConsultas.setVisible(true);
            javax.swing.JOptionPane.showMessageDialog(this, "Modo de solo lectura activado.");             
            
        } 
        else if (rolUsuario == 2) {
            // El Trabajador alimenta el sistema de cacao 
            menuGestion.setVisible(true);    
            menuConsultas.setVisible(true);
        } 
        else if (rolUsuario == 1) {
            // El Administrador tiene acceso a todo 
            menuGestion.setVisible(true);
            menuConsultas.setVisible(true);
        }
    }
