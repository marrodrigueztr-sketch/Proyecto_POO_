    private void llenarTabla() {
        javax.swing.table.DefaultTableModel modeloTab = (javax.swing.table.DefaultTableModel) tblUsuarios.getModel();
        modeloTab.setRowCount(0); 
        
        for (modelo.Usuario u : conUsuario.getListaUsuarios()) {
            modeloTab.addRow(new Object[]{
                u.getIdCedula(),
                u.getNombre(),
                u.getApellido(),
                u.getRoll() // Usamos el nombre exacto de tu atributo
            });
        }
    }
