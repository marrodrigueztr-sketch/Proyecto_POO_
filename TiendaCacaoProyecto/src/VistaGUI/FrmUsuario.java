    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            int id = Integer.parseInt(txtIdCedula.getText());
            String nom = txtNombre.getText();
            String ape = txtApellido.getText();
            double tel = Double.parseDouble(txtTelefono.getText());
            String cor = txtCorreo.getText();
            String dir = txtDireccion.getText();
            String pass = txtPassword.getText();
            String rolStr = cbxRol.getSelectedItem().toString();
            int rolInt = cbxRol.getSelectedIndex(); 

            if (rolStr.equals("Trabajador")) {
                double sueldo = Double.parseDouble(txtSalario.getText());
                String cargo = txtCargo.getText();
                // Creamos el objeto usando la clase hija Trabajador
                Trabajador nuevoT = new Trabajador(id, nom, ape, tel, cor, dir, rolInt, pass, null, cargo, sueldo);
                controlador.insertar(nuevoT); 
            } else {
                // Creamos el objeto usando la clase hija Propietario
                Propietario nuevoP = new Propietario(id, nom, ape, tel, cor, dir, rolInt, pass, null);
                controlador.insertar(nuevoP);
            }
            JOptionPane.showMessageDialog(this, "Usuario guardado con exito");
            llenarTabla(); // Función para refrescar la tabla
        } catch (HeadlessException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Verifique que los campos sean correctos.");
        }

    }//GEN-LAST:event_btnGuardarActionPerformed

