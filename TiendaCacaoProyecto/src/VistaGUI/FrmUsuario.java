    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
       try {
        int idBuscar = Integer.parseInt(txtIdCedula.getText());

        // creamos un usuario "temporal" solo para llevar el ID a la búsqueda
        Propietario usuarioTemporal = new Propietario(idBuscar, "", "", 0, "", "", 0, "", null);

        // usamos de busqueda binaria
        Usuario encontrado = controlador.consultarUno(usuarioTemporal);

        if (encontrado != null) {
            txtNombre.setText(encontrado.getNombre());
            txtApellido.setText(encontrado.getApellido());
            txtTelefono.setText(String.valueOf(encontrado.getTelefono()));
            txtCorreo.setText(encontrado.getCorreo());
            txtDireccion.setText(encontrado.getDireccion());
            txtPassword.setText(encontrado.getContrasena());

            // Seleccionamos el rol en el ComboBox
            cbxRol.setSelectedIndex(encontrado.getRoll()); 

            // Verificamos si es Trabajador usando 'instanceof'
            if (encontrado instanceof Trabajador) {
                Trabajador t = (Trabajador) encontrado;
                txtSalario.setText(String.valueOf(t.getSalario()));
                txtCargo.setText(t.getCargo());
                txtSalario.setEnabled(true);
                txtCargo.setEnabled(true);
                cbxRol.setSelectedItem("Trabajador");
            } else {
                txtSalario.setText("0");
                txtCargo.setText("N/A");
                txtSalario.setEnabled(false);
                txtCargo.setEnabled(false);
                cbxRol.setSelectedItem("Propietario"); // O Administrador según el caso
            }

            JOptionPane.showMessageDialog(this, "Usuario encontrado.");
        } else {
            JOptionPane.showMessageDialog(this, "El usuario con Cédula " + idBuscar + " no existe.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Por favor, ingrese un número de Cédula válido para buscar.");
    }

    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try {
        int idEliminar = Integer.parseInt(txtIdCedula.getText());

        // Pregunto  antes de borrar 
        int confirmacion = JOptionPane.showConfirmDialog(this, 
                "¿Está seguro que desea eliminar al usuario con cédula " + idEliminar + "?", 
                "Confirmar eliminación", 
                JOptionPane.YES_NO_OPTION);

        if (confirmacion == JOptionPane.YES_OPTION) {
            // creamos el usuario temporal solo con la  cedula
            Propietario usuarioTemporal = new Propietario(idEliminar, "", "", 0, "", "", 0, "", null);

            boolean borrado = controlador.borrar(usuarioTemporal);

            if (borrado) {
                JOptionPane.showMessageDialog(this, "Usuario eliminado correctamente.");
                btnLimpiarActionPerformed(evt); // Llama al boton limpiar
                llenarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo eliminar. Verifique que el usuario exista.");
            }
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Por favor, ingrese o busque una Cédula válida para eliminar.");
    }

        
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        try {
        int id = Integer.parseInt(txtIdCedula.getText());
        String nom = txtNombre.getText();
        String ape = txtApellido.getText();
        double tel = Double.parseDouble(txtTelefono.getText());
        String cor = txtCorreo.getText();
        String dir = txtDireccion.getText();
        String pass = txtPassword.getText();
        String rolStr = cbxRol.getSelectedItem().toString();
        int rolInt = cbxRol.getSelectedIndex(); 

        boolean modificado = false;

        if (rolStr.equals("Trabajador")) {
            double sueldo = Double.parseDouble(txtSalario.getText());
            String cargo = txtCargo.getText();
            Trabajador tModificado = new Trabajador(id, nom, ape, tel, cor, dir, rolInt, pass, null, cargo, sueldo);
            modificado = controlador.modificar(tModificado);
        } else {
            Propietario pModificado = new Propietario(id, nom, ape, tel, cor, dir, rolInt, pass, null);
            modificado = controlador.modificar(pModificado);
        }

        if (modificado) {
            JOptionPane.showMessageDialog(this, "Usuario modificado con éxito.");
            llenarTabla(); // Refrescamos la tabla para ver los cambios
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró el usuario para modificar.");
        }

    } catch (HeadlessException | NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Error: Verifique que todos los campos estén correctamente llenos.");
    }

    }//GEN-LAST:event_btnModificarActionPerformed

