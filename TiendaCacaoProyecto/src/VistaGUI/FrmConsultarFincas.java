    private void llenarTabla() {
        javax.swing.table.DefaultTableModel modeloTab = (javax.swing.table.DefaultTableModel) tblFincas.getModel();
        modeloTab.setRowCount(0); 
        
        for (modelo.Finca f : conFinca.getListaFincas()) {
            modeloTab.addRow(new Object[]{
                f.getIdFinca(),
                f.getNombreFinca(),
                f.getDireccionFinca(),
                f.getCiudad().getNombreCiudad()// Así sacamos el nombre de la ciudad asociada
            });
        }
    }

