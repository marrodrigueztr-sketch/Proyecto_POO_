    private void llenarTabla() {
    javax.swing.table.DefaultTableModel modeloTab = (javax.swing.table.DefaultTableModel) tlbCiudades.getModel();
    modeloTab.setRowCount(0);
    for (modelo.Ciudad c : controlador.getListaCiudad()) {
        modeloTab.addRow(new Object[]{
            c.getId(), 
            c.getNombreCiudad(), 
            c.getPais().getNombre()
        });
    }
}
