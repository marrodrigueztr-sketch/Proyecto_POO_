    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
        int id = Integer.parseInt(txtId.getText());
        String nombre = txtNombre.getText();

        modelo.Pais paisSeleccionado = (modelo.Pais) cmbPais.getSelectedItem();

        if (paisSeleccionado == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe registrar y seleccionar un País primero.");
            return; // Detiene la ejecución del botón
        }
        modelo.Ciudad nuevaCiudad = new modelo.Ciudad(id, nombre, paisSeleccionado);

        if (controlador.insertar(nuevaCiudad)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ciudad guardada correctamente.");
            llenarTabla();

            txtId.setText("");
            txtNombre.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Ya existe una ciudad con ese ID.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese un ID numérico válido.");
    }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
        int idEliminar = Integer.parseInt(txtId.getText());

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Está seguro que desea eliminar la ciudad con ID " + idEliminar + "?", 
                "Confirmar eliminación", 
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            modelo.Ciudad ciudadTemporal = new modelo.Ciudad(idEliminar, "", null);

            if (controlador.borrar(ciudadTemporal)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ciudad eliminada correctamente.");
                llenarTabla(); 

                txtId.setText("");
                txtNombre.setText("");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo eliminar. El ID no existe.");
            }
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese el ID de la ciudad que desea eliminar.");
    }
        
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        try {
        int idBuscar = Integer.parseInt(txtId.getText());

        modelo.Ciudad ciudadTemporal = new modelo.Ciudad(idBuscar, "", null);

        modelo.Ciudad ciudadEncontrada = controlador.consultarUno(ciudadTemporal);

        if (ciudadEncontrada != null) {
            txtNombre.setText(ciudadEncontrada.getNombreCiudad());

            cmbPais.setSelectedItem(ciudadEncontrada.getPais());

            javax.swing.JOptionPane.showMessageDialog(this, "Ciudad encontrada.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "La ciudad no existe en el sistema.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el ID de la ciudad que desea buscar.");
    }


    }//GEN-LAST:event_jButton5ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
        int id = Integer.parseInt(txtId.getText());
        String nombre = txtNombre.getText();
        modelo.Pais paisSeleccionado = (modelo.Pais) cmbPais.getSelectedItem();

        if (paisSeleccionado == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar un País.");
            return; 
        }
        modelo.Ciudad ciudadModificada = new modelo.Ciudad(id, nombre, paisSeleccionado);

        if (controlador.modificar(ciudadModificada)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ciudad modificada con éxito.");
            llenarTabla(); 

            txtId.setText("");
            txtNombre.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró la ciudad para modificar.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, busque un ID numérico válido para modificar.");
    }


    }//GEN-LAST:event_jButton2ActionPerformed

